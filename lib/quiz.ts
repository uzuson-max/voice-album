export function quizFor(label: string): QuizItem[] {
  if (!["아빠", "아버지", "아버님"].includes(label.trim())) return QUIZ;
  const out: QuizItem[] = [];
  for (let i = 0; i < Math.max(DAD_QUIZ.length, QUIZ.length); i++) {
    if (DAD_QUIZ[i]) out.push(DAD_QUIZ[i]);
    if (QUIZ[i]) out.push(QUIZ[i]);
  }
  return out;
}

